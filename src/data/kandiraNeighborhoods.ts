function lerp(start: number, end: number, t: number): number {
  return Number((start + (end - start) * t).toFixed(1));
}

function buildYearlySeries(seed: RawNeighborhoodSeed): YearlyDemographic[] {
  const years: Array<2021 | 2022 | 2023 | 2024 | 2025> = [2021, 2022, 2023, 2024, 2025];
  // Slight non-linear curve to reflect post-pandemic & 2023 migration wave in coastal/central areas
  const curveWeights = [0, 0.23, 0.54, 0.78, 1.0];

  return years.map((year, idx) => {
    const t = curveWeights[idx];
    const total = Math.round(seed.pop2021 + (seed.pop2025 - seed.pop2021) * t);
    const male = Math.round(total * seed.maleRatio);
    const female = total - male;
    const elderly65PlusPct = lerp(seed.elderly2021, seed.elderly2025, t);
    const youth0To14Pct = lerp(seed.youth2021, seed.youth2025, t);
    const summerPopulationMultiplier = lerp(seed.summerMult2021, seed.summerMult2025, t);
    const builtUpPct = lerp(seed.builtUp2021, seed.builtUp2025, t);
    const forestPct = lerp(seed.forest2021, seed.forest2025, t);
    const agriculturePct = Number((100 - builtUpPct - forestPct).toFixed(1));
    const healthAccessMin = Math.round(lerp(seed.healthMin2021, seed.healthMin2025, t));
    const educationAccessMin = Math.round(lerp(seed.eduMin2021, seed.eduMin2025, t));

    const migrationFactor = idx === 2 ? 1.18 : 0.88 + idx * 0.03;
    const netMigrationPermille = Number((seed.migrationPermille2025 * migrationFactor).toFixed(1));

    // Base raw vulnerability score (0-100)
    const elderlyComponent = Math.min(100, (elderly65PlusPct / 44) * 100);
    const socialComponent = Math.min(100, (seed.socialAidRatio / 0.11) * 100);
    const healthComponent = Math.min(100, (healthAccessMin / 25) * 100);
    const eduComponent = Math.min(100, (educationAccessMin / 20) * 100);
    const builtDelta = Math.max(0, builtUpPct - seed.builtUp2021);
    const landComponent = Math.min(
      100,
      builtDelta * 6.5 + (summerPopulationMultiplier > 5 ? 35 : 10)
    );

    const vulnerabilityRawScore = Number(
      (
        elderlyComponent * 0.3 +
        socialComponent * 0.25 +
        healthComponent * 0.2 +
        eduComponent * 0.15 +
        landComponent * 0.1
      ).toFixed(1)
    );

    return {
      year,
      total,
      male,
      female,
      elderly65PlusPct,
      youth0To14Pct,
      netMigrationPermille,
      summerPopulationMultiplier,
      builtUpPct,
      forestPct,
      agriculturePct,
      vulnerabilityRawScore,
      healthAccessMin,
      educationAccessMin,
    };
  });
}

